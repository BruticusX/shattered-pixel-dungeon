"""Sure Shot Dungeon mod: where BOTH of each redrawn hero's hands are in every frame, for gloves.
    python3 tools/heroes/glove_hands.py   -> sprites/HeroHDGloves.java
Reads the finished sheets (row 0, no armor) so every frame the game shows is covered, extra
animations included. A hand is a patch of skin below the beard line; only visible hands count."""
import re, sys
import numpy as np
from PIL import Image
from scipy import ndimage
sys.path.insert(0, "tools/heroes")
import hands

SRC = "tools/spritecook/heroes/"
JAVA = "core/src/main/java/com/shatteredpixel/shatteredpixeldungeon/sprites/"
CLASSES = ["warrior", "mage", "rogue", "huntress", "duelist", "cleric"]
out = {}
for cls in CLASSES:
    FS = Image.open(SRC + f"{cls}_idle_sheet.png").height
    hands.FS = FS
    hands.learn(Image.open(SRC + f"{cls}_idle_sheet.png").convert("RGBA").crop((0, 0, FS, FS)))
    sheet = Image.open(f"core/src/main/assets/sprites/hero_hd_{cls}.png").convert("RGBA")
    F = sheet.height // 7
    n = sheet.width // F
    idle_bb = sheet.crop((0, 0, F, F)).getchannel("A").getbbox()
    body_h = idle_bb[3] - idle_bb[1]
    rows = []
    for f in range(n):
        fr = sheet.crop((f * F, 0, f * F + F, F))
        a = np.array(fr)
        bb = fr.getchannel("A").getbbox()
        skin = np.zeros((F, F), bool)
        if bb:
            # below the face: a hand is never above the shoulders here (beard line at ~33% of the
            # standing height; low poses like death frames are skipped by the size test)
            top = idle_bb[1] + body_h * 0.33
            for y in range(int(top), F):
                for x in range(F):
                    if a[y, x, 3] >= 200 and hands.is_skin(tuple(int(v) for v in a[y, x])):
                        skin[y, x] = True
        lab, k = ndimage.label(skin, np.ones((3, 3), bool))
        blobs = []
        if k:
            sz = ndimage.sum(skin, lab, range(1, k + 1))
            cm = ndimage.center_of_mass(skin, lab, range(1, k + 1))
            # a hand is a small patch; bigger skin-coloured areas are hair or a bare arm
            blobs = sorted([(s, c) for s, c in zip(sz, cm) if 4 <= s <= 45], key=lambda b: -b[0])[:2]
        pts = [(round(c[1], 1), round(c[0], 1)) for s, c in blobs]
        while len(pts) < 2: pts.append((-1, -1))
        rows.append(pts)
    out[cls] = rows
    print(cls, n, "frames,", sum(1 for r in rows for p in r if p[0] >= 0), "hands found")

def jf(v): return "%.1ff" % v
lic = open(JAVA + "HeldWeapon.java").read(); lic = lic[:lic.index("package")]
cases = []
for c, rows in out.items():
    arrs = [", ".join(jf(r[i][j]) for r in rows) for i in (0, 1) for j in (0, 1)]
    cases.append(f'\t\tcase "{c}": return new float[][]{{{{{arrs[0]}}}, {{{arrs[1]}}}, {{{arrs[2]}}}, {{{arrs[3]}}}}};')
open(JAVA + "HeroHDGloves.java", "w").write(lic + """package com.shatteredpixel.shatteredpixeldungeon.sprites;

//MOD: GENERATED by tools/heroes/glove_hands.py, do not edit by hand.
//Per redrawn hero and frame: both visible hands {x1[], y1[], x2[], y2[]} (-1 = not visible), for gloves.
public class HeroHDGloves {

	public static float[][] of( String cls ){
		switch (cls) {
""" + "\n".join(cases) + """
		default: return null;
		}
	}
}
""")
