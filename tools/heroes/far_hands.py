"""Sure Shot Dungeon mod: where each redrawn hero's OTHER hand is, frame by frame (for gloves, which
are worn on both hands). python3 tools/heroes/far_hands.py  -> sprites/HeroHDFarHands.java
Only frames where the hand's skin is actually visible get a position (-1 elsewhere)."""
import re, sys
from PIL import Image
sys.path.insert(0, "tools/heroes")
import hands

SRC = "tools/spritecook/heroes/"
JAVA = "core/src/main/java/com/shatteredpixel/shatteredpixeldungeon/sprites/"
ANIMS = [("idle", 8), ("run", 10), ("attack", 8), ("death", 12)]
THICKEN = {"duelist"}
CLASSES = ["warrior", "mage", "rogue", "huntress", "duelist", "cleric"]

def near_table(cls):
    t = open(JAVA + f"HeroHD{cls.capitalize()}.java").read()
    arrs = re.findall(r"new float\[\]\{([^}]*)\}", t)
    hx = [float(v.strip().rstrip("f")) for v in arrs[0].split(",")]
    hy = [float(v.strip().rstrip("f")) for v in arrs[1].split(",")]
    return hx, hy

out = {}
for cls in CLASSES:
    FS = Image.open(SRC + f"{cls}_idle_sheet.png").height
    hands.FS = FS
    idle0 = Image.open(SRC + f"{cls}_idle_sheet.png").convert("RGBA").crop((0, 0, FS, FS))
    hands.learn(idle0)
    nx, ny = near_table(cls)
    xs, ys = [], []
    i = 0
    for name, k in ANIMS:
        im = Image.open(SRC + f"{cls}_{name}_sheet.png").convert("RGBA")
        if cls in THICKEN:
            hands.thicken_arms(im, k)
        for f in range(k):
            h = hands.front_hand(im, f) if name != "death" else None
            ok = h is not None and h[1] >= 20 and nx[i] >= 0
            if ok and abs(h[0] - nx[i]) < 7 and abs(h[1] - ny[i]) < 7:
                ok = False   # the same hand the weapon table already tracks
            xs.append(round(h[0], 1) if ok else -1)
            ys.append(round(h[1], 1) if ok else -1)
            i += 1
    out[cls] = (xs, ys)
    print(cls, sum(1 for v in xs if v >= 0), "/", len(xs), "frames with a far hand")

def jf(v): return "%.1ff" % v
lic = open(JAVA + "HeldWeapon.java").read(); lic = lic[:lic.index("package")]
body = "\n".join(f'\t\tcase "{c}": return new float[][]{{{{{", ".join(jf(v) for v in xs)}}}, {{{", ".join(jf(v) for v in ys)}}}}};'
                 for c, (xs, ys) in out.items())
open(JAVA + "HeroHDFarHands.java", "w").write(lic + f"""package com.shatteredpixel.shatteredpixeldungeon.sprites;

//MOD: GENERATED by tools/heroes/far_hands.py, do not edit by hand.
//Per redrawn hero, per frame: where the hand that does NOT hold the weapon is ({{x[], y[]}}, -1 = not visible).
public class HeroHDFarHands {{

	public static float[][] of( String cls ){{
		switch (cls) {{
{body}
		default: return null;
		}}
	}}
}}
""")
