"""Sure Shot Dungeon mod: build AuraMaps.java from items.png.

For every weapon sprite (rows 7-11) it records the blade/head pixels, so enchantment
particles spawn only along the blade. For every armor sprite (row 12) it records the
outline pixels, so glyph auras hug the armor's silhouette.

Re-run whenever weapon or armor sprites change:
    python3 tools/gen_aura_maps.py
"""
from PIL import Image

ROOT = "core/src/main"
SHEET = f"{ROOT}/assets/sprites/items.png"
OUT = f"{ROOT}/java/com/shatteredpixel/shatteredpixeldungeon/effects/AuraMaps.java"
SIZE, COLS = 16, 16
BLADE_ROWS = [7, 8, 9, 10, 11]
ARMOR_ROWS = [12]


def is_metal(r, g, b):
    return max(r, g, b) - min(r, g, b) <= 12 and (r + g + b) / 3 >= 60


def slot(im, idx):
    c, r = idx % COLS, idx // COLS
    return im.crop((c * SIZE, r * SIZE, c * SIZE + SIZE, r * SIZE + SIZE)).load()


def blade_pixels(px):
    metal, solid = [], []
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b, a = px[x, y]
            if a < 255 or max(r, g, b) < 40:
                continue
            solid.append(y * SIZE + x)
            if is_metal(r, g, b):
                metal.append(y * SIZE + x)
    # sprites with little grey (gold hammer, red bloodletter, wooden bows) use the whole body
    return metal if len(metal) >= 5 else solid


def outline_pixels(px):
    out = []
    for y in range(SIZE):
        for x in range(SIZE):
            if px[x, y][3] < 255:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if not (0 <= nx < SIZE and 0 <= ny < SIZE) or px[nx, ny][3] < 255:
                    out.append(y * SIZE + x)
                    break
    return out


def main():
    im = Image.open(SHEET).convert("RGBA")
    blade, outline = {}, {}
    for rows, target, fn in ((BLADE_ROWS, blade, blade_pixels), (ARMOR_ROWS, outline, outline_pixels)):
        for row in rows:
            for c in range(COLS):
                idx = (row - 1) * COLS + c
                pts = fn(slot(im, idx))
                if pts:
                    target[idx] = pts

    def block(name, data):
        lines = [f"\t\t{name}.put({k}, new short[]{{{','.join(map(str, v))}}});" for k, v in sorted(data.items())]
        return "\n".join(lines)

